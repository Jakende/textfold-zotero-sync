const assert = require('node:assert/strict');
const c = require('./core.js');
assert.equal(c.normalized('oﬃce – Zeilen-\numbruch'),'officezeilenumbruch');
const chars = [...'One unique passage in this document.'].map((s,i)=>({c:s,inlineRect:[i,30,i+1,40]}));
const spans=c.matches(c.pageIndex(chars),'One unique passage in this document.');
assert.deepEqual(spans,[{start:0,end:35}]);
assert.equal(c.selection(chars,0,35,2).position.pageIndex,2);
assert.equal(c.matches(c.pageIndex([...chars,...chars]),'One unique passage in this document.').length,2);
assert.equal(c.matches(c.pageIndex(chars),'tiny').length,0);
assert.throws(()=>c.selection([{c:'x',inlineRect:[1,3,0,4]}],0,1,0));
assert.equal(c.decision({source:'a',target:'b'},{},'b','a'),'unchanged');
assert.equal(c.decision({source:'a',target:'b'},{},'b','new'),'update');
assert.equal(c.decision({source:'a',target:'b'},{},'manual edit','new'),'conflict');
assert.equal(c.decision({source:'a',target:'b'},{deleted:true},'b','a'),'deleted');
assert.equal(c.decision({source:'a',target:'b'},null,null,'a'),'deleted');
const note={id:'n-one',kind:'ask',text:'<script>unsafe</script>',thread:[{q:'Question',a:'Answer [[u1]]'}]};
assert(c.noteHTML('paper',note,'Whole paper').includes('&lt;script&gt;'));
assert(!c.noteHTML('paper',note).includes('<script>'));
assert.equal(c.sourceSignature({...note,updated:'old'}),c.sourceSignature({...note,updated:'new'}));
assert.notEqual(c.sourceSignature(note),c.sourceSignature({...note,text:'edited'}));
console.log('15 checks passed: matching, ambiguity, geometry, idempotency, conflict/deletion handling, HTML escaping.');
